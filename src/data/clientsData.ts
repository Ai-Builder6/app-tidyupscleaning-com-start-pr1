/**
 * Merge existing scheduled jobs or leads into clients database without duplicates
 */
export function mergeJobsIntoClients(existingClients: ClientRecord[], scheduledJobs: any[] = []): ClientRecord[] {
  const clientMap = new Map<string, ClientRecord>();
  
  // Seed with existing clients
  existingClients.forEach((c) => {
    const key = (c.phone || c.name).replace(/\D/g, '') || c.name.toLowerCase().trim();
    clientMap.set(key, c);
  });

  // Merge scheduled jobs
  scheduledJobs.forEach((job) => {
    if (!job?.clientName && !job?.clientPhone) return;
    const phoneDigits = (job.clientPhone || '').replace(/\D/g, '');
    const key = phoneDigits || (job.clientName || '').toLowerCase().trim();

    const existing = clientMap.get(key);
    if (existing) {
      // Enrich with missing info
      clientMap.set(key, {
        ...existing,
        address: existing.address || job.serviceAddress,
        latestServiceDate: existing.latestServiceDate || job.startAt?.split('T')[0],
        totalJobs: Math.max(existing.totalJobs || 1, 2),
      });
    } else {
      clientMap.set(key, {
        id: `cli-auto-${job.id || Math.random().toString(36).slice(2, 8)}`,
        name: job.clientName || 'Scheduled Client',
        phone: job.clientPhone || '(780) 555-0100',
        secondaryPhone: job.secondaryPhone || '',
        address: job.serviceAddress || 'Edmonton, AB',
        city: 'Edmonton',
        province: 'AB',
        postalCode: 'T5J 0A1',
        verdict: 'Client',
        tags: ['jobber-scheduled', job.serviceType?.toLowerCase().replace(' ', '-') || 'cleaning'],
        isJobberLinked: true,
        jobberId: `jobber-auto-${job.id || 'visit'}`,
        totalJobs: 1,
        latestServiceDate: job.startAt?.split('T')[0] || new Date().toISOString().split('T')[0],
        notes: `Imported from scheduled visit ${job.visitNumber || ''}`,
        source: 'Jobber',
        createdAt: new Date().toISOString(),
        updatedAt: new Date().toISOString(),
      });
    }
  });

  return Array.from(clientMap.values());
}
